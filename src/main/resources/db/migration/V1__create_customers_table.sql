CREATE TABLE customers
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    cpf  VARCHAR(11),
    cnpj VARCHAR(14),

    CONSTRAINT customers_cpf_unique UNIQUE (cpf),
    CONSTRAINT customers_cnpj_unique UNIQUE (cnpj),

    CONSTRAINT customers_exactly_one_document_check
        CHECK (
            (cpf IS NOT NULL AND cnpj IS NULL)
                OR
            (cpf IS NULL AND cnpj IS NOT NULL)
            ),

    CONSTRAINT customers_cpf_format_check
        CHECK (cpf IS NULL OR cpf ~ '^[0-9]{11}$'
) ,

    CONSTRAINT customers_cnpj_format_check
        CHECK (cnpj IS NULL OR cnpj ~ '^[0-9]{14}$')
);